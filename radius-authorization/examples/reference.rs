//! Generate the settings catalog from the same metadata as CLI and GXWI.
use radius_authorization::{Kind, FIELDS};
fn main() {
    let mode = std::env::args().nth(1).unwrap_or_else(|| "markdown".into());
    if !matches!(mode.as_str(), "markdown" | "regman") {
        eprintln!("expected markdown or regman");
        std::process::exit(1);
    }
    if mode == "markdown" {
        println!("<!-- Generated by radius-authorization/examples/reference.rs; do not hand-edit. -->\n\n| Setting | Registry value | Standard attribute |\n| --- | --- | --- |");
    }
    for field in FIELDS {
        let wide = field.name.ends_with("BitsPerSecond") || field.name.ends_with("BurstBytes");
        let ty = match field.kind {
            Kind::Number if wide => "REG_SZ (unsigned decimal u64)",
            Kind::Number => "REG_DWORD",
            Kind::Boolean => "REG_DWORD (0 or 1)",
            Kind::Text => "REG_SZ",
            Kind::List => "REG_MULTI_SZ",
        };
        let attribute = field.attribute.map(|a| a.to_string()).unwrap_or_else(|| {
            if field.name == "ServiceLabel" {
                "Local metadata".into()
            } else {
                "Equipment mapping".into()
            }
        });
        if mode == "markdown" {
            println!("| `{}` | {ty} | {attribute} |", field.name);
        } else {
            println!("--- machine\\software\\radius\\accessprofiles\\<guid> {}\ncanonical: Machine\\Software\\Radius\\AccessProfiles\\<guid> {}\ntype: {}\ndefault: (absent, no profile override)\nvalid: {}\napplies: live (subsequent authentication and qualified session controls)\n\n{}. Part of {}.\n\nSee the Access Profile Settings reference for validation, encoding and\nqualification limits. Standard attribute: {attribute}.\n",field.name.to_lowercase(),field.name,ty.split(' ').next().unwrap(),match field.kind {Kind::Number if wide=>"positive unsigned decimal u64",Kind::Number=>"bounded DWORD; zero allowed only for priority and privilege",Kind::Boolean=>"0 or 1",Kind::Text=>"nonempty bounded text, validated for this setting",Kind::List=>"1–32 distinct nonempty validated strings"},field.label,field.group);
        }
    }
}
